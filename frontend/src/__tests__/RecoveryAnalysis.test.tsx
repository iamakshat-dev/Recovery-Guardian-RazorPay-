import { render, screen, within } from "@testing-library/react";
import { describe, expect, it } from "vitest";
import { RecoveryAnalysis } from "../pages/RecoveryAnalysis";
import { RecoveryVsSafetyChart } from "../components/recovery/RecoveryVsSafetyChart";
import { snapshot } from "../data/snapshot";

describe("RecoveryAnalysis — renders and shows all four strategies", () => {
  it("renders the page and all four strategy names", () => {
    render(<RecoveryAnalysis />);
    expect(screen.getByRole("heading", { name: /recovery, constrained by safety/i })).toBeInTheDocument();
    const comparisonSection = screen.getByRole("heading", { name: /strategy comparison/i }).closest("section");
    const scoped = within(comparisonSection as HTMLElement);
    expect(scoped.getByText("Naive Retry")).toBeInTheDocument();
    expect(scoped.getByText("Rules-only")).toBeInTheDocument();
    expect(scoped.getByText("Guardian")).toBeInTheDocument();
    expect(scoped.getByText("No Action")).toBeInTheDocument();
  });
});

describe("RecoveryAnalysis — artifact-backed values", () => {
  it("matches the live snapshot's Day 10 strategy table exactly, not hardcoded numbers", () => {
    render(<RecoveryAnalysis />);
    const g = snapshot.day10.strategyTable.GUARDIAN;
    const r = snapshot.day10.strategyTable.RULES_ONLY;
    // Sanity: Rules-only recovers more than Guardian (the actual finding).
    expect(r.simulatedAmountRecovered).toBeGreaterThan(g.simulatedAmountRecovered);
    expect(g.duplicateChargeRiskCount).toBe(0);

    const body = document.body.textContent ?? "";
    expect(body).toContain(g.transactions.toString());
  });

  it("never claims Guardian has the highest recovery or is universally superior", () => {
    render(<RecoveryAnalysis />);
    const body = document.body.textContent ?? "";
    expect(body).not.toMatch(/guardian.{0,40}(highest|best|maximum|universally optimal)/i);
    expect(body).not.toMatch(/production[- ]proven/i);
    expect(body).toMatch(/does not maximize raw recovery/i);
  });
});

describe("RecoveryAnalysis — provenance", () => {
  it("shows SIMULATED provenance visibly, not buried", () => {
    render(<RecoveryAnalysis />);
    expect(screen.getAllByText("SIMULATED").length).toBeGreaterThan(0);
    expect(
      screen.getByText(/generated by the Day 8 synthetic outcome simulator/i)
    ).toBeInTheDocument();
  });

  it("never labels simulated recovery as observed/actual/production revenue (the disclaimer may still name the rejected terms while negating them)", () => {
    render(<RecoveryAnalysis />);
    const body = document.body.textContent ?? "";
    // Forbidden: a POSITIVE claim pairing a recovered amount with these
    // terms. Allowed, and present: the honest disclaimer negating them
    // ("never observed Razorpay production recovery", "never actual
    // revenue"). Check for the specific overclaiming phrasing directly
    // rather than banning the words from co-occurring at all.
    expect(body).not.toMatch(/actual revenue recovered/i);
    expect(body).not.toMatch(/production recovery of ₹/i);
    expect(body).not.toMatch(/observed recovery of ₹/i);
    expect(body).not.toMatch(/guaranteed recovery/i);
    expect(body).toMatch(/never observed razorpay production recovery/i);
  });
});

