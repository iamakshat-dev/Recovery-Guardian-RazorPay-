describe("RecoveryAnalysis — seed sensitivity uses only confirmed data", () => {
  it("shows exactly the seeds present in the live snapshot, no invented seeds", () => {
    render(<RecoveryAnalysis />);
    const seeds = [String(snapshot.day10.primarySeed), ...snapshot.day10.sensitivitySeeds.map(String)];
    expect(seeds).toEqual(["42", "43", "44"]);
    const seedSection = screen.getByRole("heading", { name: /seed sensitivity/i }).closest("section");
    const scoped = within(seedSection as HTMLElement);
    for (const seed of seeds) {
      expect(scoped.getByText(`Seed ${seed}`)).toBeInTheDocument();
    }
  });

  it("Guardian duplicate-charge risk is zero for every seed shown", () => {
    const seeds = [String(snapshot.day10.primarySeed), ...snapshot.day10.sensitivitySeeds.map(String)];
    const seedSensitivity: Record<string, { GUARDIAN: { duplicateChargeRiskCount: number } }> = snapshot.day10.seedSensitivity;
    for (const seed of seeds) {
      expect(seedSensitivity[seed].GUARDIAN.duplicateChargeRiskCount).toBe(0);
    }
  });
});

describe("RecoveryAnalysis — root-cause data is artifact-backed, not fabricated", () => {
  it("renders all six root causes from the live snapshot", () => {
    render(<RecoveryAnalysis />);
    const rootCauseSection = screen.getByRole("heading", { name: /root-cause breakdown/i }).closest("section");
    const scoped = within(rootCauseSection as HTMLElement);
    for (const rc of Object.keys(snapshot.day10.rootCauseTable)) {
      expect(scoped.getAllByText(rc).length).toBeGreaterThan(0);
    }
  });

  it("CARD_DECLINE + INSUFFICIENT_FUNDS combined count matches the live snapshot (99 transactions)", () => {
    render(<RecoveryAnalysis />);
    const combined = snapshot.day10.combinedCardDeclineInsufficientFunds.GUARDIAN;
    expect(combined.transactions).toBe(99);
    expect(screen.getByText(new RegExp(`${combined.transactions} transactions`))).toBeInTheDocument();
  });

  it("INFRASTRUCTURE Guardian action split matches the live snapshot (43 DEFER_RETRY / 12 HUMAN_REVIEW)", () => {
    render(<RecoveryAnalysis />);
    const infra = snapshot.day10.rootCauseTable.INFRASTRUCTURE.GUARDIAN;
    expect(infra.actionDistribution.DEFER_RETRY).toBe(43);
    expect(infra.actionDistribution.HUMAN_REVIEW).toBe(12);
    expect(screen.getByText(/43 DEFER_RETRY/)).toBeInTheDocument();
    expect(screen.getByText(/12 HUMAN_REVIEW/)).toBeInTheDocument();
  });

  it("uses the actual policy threshold from the snapshot, not a hardcoded 0.75", () => {
    render(<RecoveryAnalysis />);
    expect(snapshot.day12.infrastructureConfidenceThreshold).toBe(0.75);
    expect(screen.getByText(/75% confidence threshold/)).toBeInTheDocument();
  });
});

